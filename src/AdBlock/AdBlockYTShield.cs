        public static bool IsExplicitAdDomain(string urlOrDomain)
        {
            if (string.IsNullOrEmpty(urlOrDomain)) return false;
            string domain = UrlHelper.NormalizeDomain(urlOrDomain);
            if (string.IsNullOrEmpty(domain)) return false;

            for (int i = 0; i < AdditionalBlockedDomains.Length; i++)
