                string adDom = AdditionalBlockedDomains[i];
                if (domain.Equals(adDom, StringComparison.OrdinalIgnoreCase) ||
                    domain.EndsWith("." + adDom, StringComparison.OrdinalIgnoreCase))
                {
                    return true;
                }
            }
            return false;
